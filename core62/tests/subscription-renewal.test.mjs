import assert from "node:assert/strict";
import {createJournalSession,parseJournal} from "../src/journal.mjs";
const session=createJournalSession();
const apply=(t,f)=>assert.equal(session.apply(t,f).status,"APPLIED_SHADOW");
const rule={id:"sub",kind:"subscription",direction:"out",amountMinor:1000,start:"2026-01-01",day:31,everyMonths:1,count:null,end:null,name:"synthetic"};
apply("rule",rule);
apply("pay-occurrence",{scheduleId:"sub",due:"2026-01-31",id:"payment",amountMinor:1000,date:"2026-01-31",accountId:null,note:"paid"});
const before=session.exportJournal();
assert.equal(session.apply("subscription-renew",{scheduleId:"sub",id:"new",start:"2026-02-27",amountMinor:1500}).code,"renewal-must-match-due-date");
assert.deepEqual(session.exportJournal(),before);
apply("subscription-renew",{scheduleId:"sub",id:"new",start:"2026-02-28",amountMinor:1500});
let v=session.view({month:"2026-02",asOf:"2026-02-01",through:"2026-03-31"});
assert.equal(v.projection.status,"PREVIEW_ONLY");
assert.deepEqual(v.occurrences.map(x=>[x.due,x.amountMinor]),[["2026-01-31",1000],["2026-02-28",1500],["2026-03-31",1500]]);
assert.equal(v.projection.quality.cents.confirmedOut,1000);
assert.equal(v.projection.quality.cents.plannedOut,3000);
apply("materialize",{scheduleId:"new",due:"2026-03-31"});
assert.equal(session.apply("subscription-stop",{scheduleId:"new",end:"2026-03-01"}).code,"subscription-has-materialized-future");
apply("subscription-stop",{scheduleId:"new",end:"2026-03-31"});
v=session.view({month:"2026-04",asOf:"2026-04-01",through:"2026-04-30"});
assert.equal(v.projection.status,"PREVIEW_ONLY");assert.ok(v.occurrences.every(o=>o.due<"2026-04-01"));
assert.deepEqual(parseJournal(JSON.stringify(session.exportJournal())).snapshot(),session.snapshot());
console.log("Subscription renewal at exact due date, preserved paid history, future obligation guard and replay passed.");
